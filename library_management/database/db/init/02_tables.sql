-- 02_tables.sql

-- Set search path to use our auth schema
SET search_path TO auth;

-- Role table
CREATE TABLE IF NOT EXISTS auth.role (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(255) NOT NULL UNIQUE
);

-- Users table
CREATE TABLE IF NOT EXISTS auth.user (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(64) NOT NULL,
    last_name VARCHAR(64) NOT NULL,
    phone VARCHAR(15) NOT NULL,
    email VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- User roles table
CREATE TABLE IF NOT EXISTS auth.user_roles (
    --id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES auth.user(id) ON DELETE CASCADE,
    role_id bigint NOT NULL REFERENCES auth.role(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
 
-- Login credentials table
-- Note: user_id is unique to ensure one-to-one relationship between user and login credentials
CREATE TABLE IF NOT EXISTS auth.login_credential (
    --id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES auth.user(id) ON DELETE CASCADE UNIQUE,
    password_hash TEXT NOT NULL,
    salt VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Refresh token table
-- TIMESTAMPTZ (Postgresql) and TIMESTAMP WITH TIME ZONE are the same
CREATE TABLE IF NOT EXISTS auth.refresh_token (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES auth.user(id) ON DELETE CASCADE,
    token VARCHAR(255) NOT NULL,
    
    -- Token lifecycle
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    
    -- Revocation and Rotation tracking
    revoked_at TIMESTAMP WITH TIME ZONE, -- If NULL, the token is technically "active"
    
    -- Self-referencing foreign key to track the chain of token rotation (For Reuse Detection)
    replaced_by_token_id bigint REFERENCES auth.refresh_token(id) ON DELETE SET NULL
);

---- Indexes ----

-- Allow multiple roles per user, but ensure that each user-role combination is unique
CREATE UNIQUE INDEX IF NOT EXISTS idx_user_roles_user_role 
    ON auth.user_roles(user_id, role_id);

-- Index token column in refresh_token table for faster lookups
CREATE INDEX IF NOT EXISTS idx_refresh_token_token 
    ON auth.refresh_token(token);

-- Index user_id column in refresh_token table for faster lookups of active tokens
CREATE INDEX IF NOT EXISTS idx_refresh_token_user 
    ON auth.refresh_token(user_id) where revoked_at IS NULL;

-- Note: The unique constraint on the username column in the login_credential table is already enforced by the PRIMARY KEY constraint, so an additional unique index is not necessary.
